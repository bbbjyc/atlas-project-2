export const WAR_SHOP = toCats(RAW_WAR);   // 전쟁모드: 무기 · 갑옷 · 물약
export const ITEM: Record<string, Item> = Object.fromEntries([...SHOP, ...WAR_SHOP].flatMap(c => c.items.map(it => [it.name, it])));
export const consumable = (it: Item) => it.kind === 'food' || it.kind === 'potion';   // 음식·물약은 계속 살 수 있다

// 아이템 그림: 이름으로 그림(a-…)을 고르고 색은 --a/--b 로. 전설 이상은 얼굴, 희귀 이상은 반짝이(o-…)를 얹는다
export function itemArt(it: Item) {
  const arch = ART_RULES[it.cat].find(([re]) => re.test(it.name))![1];
  let a: string | undefined, b: string | undefined;
  if (it.kind === 'potion') { a = FX_COLOR[it.effects[0][0]]; b = it.effects[1] && FX_COLOR[it.effects[1][0]]; }
  else {
    const word = it.g === 'n' ? it.color : Object.keys(ART_COLOR).find(k => it.name.includes(k));
    a = (word && ART_COLOR[word]) || (word && TINT[word] ? `color-mix(in srgb,${TINT[word]} 72%,#fff)` : undefined);
  }
  if (it.g === 'l') b ||= '#ffd84d';
  if (it.g === 'p') b ||= '#ffb3e6';
  const style: Record<string, string> = {};
  if (a) style['--a'] = a;
  if (b) style['--b'] = b;
  return { arch, style, face: it.g === 'l' || it.g === 'p' ? FACE[arch] : undefined, overlay: it.g === 'n' ? undefined : `o-${it.g}` };
}
