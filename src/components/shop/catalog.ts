// ── 화면에서 쓰기 쉽게 한 줄 형식을 이름 붙은 값으로 ──
export interface Item {
  name: string; g: Grade; price: number; cat: string; kind: Kind;
  val: number;        // 펫: 애정·경험치
  atk: number; def: number;   // 장비
  effects: Fx[];      // 물약
  color?: string;     // 일반 아이템의 색·맛 이름
  fx?: string;        // 프리미엄 고유 효과
}
export interface Category { key: string; label: string; icon: string; kind: Kind; stat?: string; items: Item[] }

function toItem(cat: string, kind: Kind, r: Raw): Item {
  const [name, g, price] = r as [string, Grade, number];
  const base = { name, g, price, cat, kind, val: 0, atk: 0, def: 0, effects: [] as Fx[] };
  if (kind === 'gear') return { ...base, atk: r[3] as number, def: r[4] as number, color: (r[5] as string) || undefined, fx: (r[6] as string) || undefined };
  if (kind === 'potion') return { ...base, effects: r[3] as Fx[], fx: (r[4] as string) || undefined };
  return { ...base, val: r[3] as number, color: (r[4] as string) || undefined };
}
const toCats = (raw: Record<string, RawCat>): Category[] =>
  Object.entries(raw).map(([key, c]) => ({ key, label: c.label, icon: c.icon, kind: c.kind, stat: c.stat, items: c.items.map(r => toItem(key, c.kind, r)) }));

